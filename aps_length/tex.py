"""Small, source-based LaTeX helpers, without macro expansion.

Offsets refer to the original source. Comments are masked before structural
matching so that removing them does not move commands or join unrelated tokens.
This is deliberately not a TeX interpreter: verbatim text, conditional branches,
and environments generated by macros require manual inspection.
"""

from dataclasses import dataclass
import re


DEFAULT_STOP_COMMENT = '!STOP-APS-LENGTH!'
DISPLAY_MATH_ENVS = (
    'equation', 'eqnarray', 'align', 'alignat', 'flalign', 'gather',
    'multline', 'displaymath',
)
DEFAULT_IGNORE_ENVS = DISPLAY_MATH_ENVS + (
    'abstract', 'acknowledgments', 'acknowledgements', 'thebibliography',
)
TABULAR_ENVS = ('tabular', 'tabular*', 'tabularx')
ENVIRONMENT_RE = re.compile(
    r'\\(?P<kind>begin|end)\s*\{\s*(?P<name>[\w*@-]+)\s*\}')
GRAPHICS_RE = re.compile(r'\\includegraphics\*?(?![A-Za-z])')
INPUT_RE = re.compile(r'\\(?:input|include)\s*\{([^{}]+)\}')
TIKZ_RE = re.compile(r'\\(?:begin\s*\{tikzpicture\}|tikz\b)')
CONTROL_SEQUENCE_RE = re.compile(r'\\(?:[A-Za-z]+|.)')
TABLE_RULE_RE = re.compile(
    r'\\(?:hline|toprule|midrule|bottomrule)\b(?:\[[^\]]*\])?'
    r'|\\(?:cline|cmidrule)\b(?:\([^)]*\))?\s*\{[^{}]*\}'
    r'|\\addlinespace\b(?:\[[^\]]*\])?')


@dataclass(frozen=True)
class Environment:
    name: str
    start: int
    body_start: int
    body_end: int
    end: int


@dataclass(frozen=True)
class Graphic:
    filename: str
    start: int
    end: int


@dataclass(frozen=True)
class Row:
    start: int
    end: int
    environments: tuple[Environment, ...]


class ParsedSource:
    """Source text and one index of all its literal, nested environments.

    The comment mask and offsets are shared by every counting pass. Construct
    a new instance if the source changes; all spans belong to this exact text.
    This also accepts fragments without a document environment.
    """

    def __init__(self, source):
        self.source = source
        self.active = mask_comments(source)
        stack = []
        spans = []
        for match in ENVIRONMENT_RE.finditer(self.active):
            if is_escaped(self.active, match.start()):
                continue
            name = match['name']
            if match['kind'] == 'begin':
                stack.append(match)
            elif not stack or stack[-1]['name'] != name:
                line = source.count('\n', 0, match.start()) + 1
                raise ValueError(r'Unmatched \end{%s} near line %d' % (name, line))
            else:
                begin = stack.pop()
                spans.append(Environment(name, begin.start(), begin.end(),
                                         match.start(), match.end()))
        if stack:
            begin = stack[-1]
            line = source.count('\n', 0, begin.start()) + 1
            raise ValueError(r'Could not find \end{%s} for environment at line %d' %
                             (begin['name'], line))
        self.environments = tuple(sorted(spans, key=lambda span: span.start))
        self._environment_at = {span.start: span for span in self.environments}

    def find_environments(self, names, *, within=None, outermost=False):
        """Select environment names, including starred variants, from the index.

        With ``within``, search only the supplied environment's body. With
        ``outermost``, omit matches contained in another selected environment.
        """
        names = set(names)
        start, end = (within.body_start, within.body_end) if within else (0, len(self.source))
        spans = []
        for span in self.environments:
            if span.start < start or span.end > end:
                continue
            if span.name not in names and span.name.removesuffix('*') not in names:
                continue
            if outermost and spans and span.start < spans[-1].end:
                continue
            spans.append(span)
        return spans


def is_escaped(source, offset):
    """Whether a character is preceded by an odd run of backslashes."""
    start = offset
    while start > 0 and source[start - 1] == '\\':
        start -= 1
    return (offset - start) % 2 == 1


def split_latex_comment(line):
    for match in re.finditer('%', line):
        if not is_escaped(line, match.start()):
            return line[:match.start()], line[match.end():]
    return line, None


def strip_latex_comment(line):
    """Keep TeX's comment terminator and the original newline convention."""
    code, comment = split_latex_comment(line)
    if comment is None:
        return line
    newline = re.search(r'(\r\n|\n|\r)$', comment)
    return code + '% ' + (newline.group() if newline else '')


def has_stop_comment(line, marker):
    _, comment = split_latex_comment(line)
    return bool(marker and comment is not None and marker in comment)


def mask_comments(source):
    parts = []
    for line in source.splitlines(keepends=True):
        code, comment = split_latex_comment(line)
        parts.append(code)
        if comment is not None:
            parts.append(re.sub(r'[^\r\n]', ' ', '%' + comment))
    return ''.join(parts)


def remove_comments(source):
    """Remove comments including their newline, as TeX does."""
    return ''.join(split_latex_comment(line)[0]
                   for line in source.splitlines(keepends=True))


def command_matches(pattern, source):
    """Ignore comments and command starts preceded by an odd backslash run."""
    active = mask_comments(source)
    return (match for match in re.finditer(pattern, active)
            if not is_escaped(active, match.start()))


def blank_spans(source, spans):
    """Blank source ranges, retaining line boundaries and separating words."""
    chars = list(source)
    for start, end in spans:
        for offset in range(start, end):
            if chars[offset] not in '\r\n':
                chars[offset] = ' '
    return ''.join(chars)


def skip_space(source, offset):
    while offset < len(source) and source[offset].isspace():
        offset += 1
    return offset


def read_group(source, offset, opener='{', closer='}'):
    """Read a balanced TeX argument, including nested braces in options."""
    offset = skip_space(source, offset)
    if offset >= len(source) or source[offset] != opener:
        raise ValueError('Expected %r near: %s' % (opener, source[offset:offset + 80]))
    start = offset + 1
    depth = 1
    braces = 0
    for i in range(start, len(source)):
        if is_escaped(source, i):
            continue
        char = source[i]
        if opener != '{':
            if char == '{':
                braces += 1
            elif char == '}':
                braces -= 1
            if braces:
                continue
        if char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return source[start:i], i + 1
    raise ValueError('Unclosed %r argument near: %s' % (opener, source[offset:offset + 80]))


def includegraphics_commands(source):
    active = mask_comments(source)
    commands = []
    offset = 0
    for match in GRAPHICS_RE.finditer(active):
        if match.start() < offset or is_escaped(active, match.start()):
            continue
        offset = skip_space(active, match.end())
        while offset < len(active) and active[offset] == '[':
            _, offset = read_group(active, offset, '[', ']')
            offset = skip_space(active, offset)
        argument_start = offset
        try:
            _, offset = read_group(active, offset)
        except ValueError as error:
            raise ValueError('Could not parse includegraphics near: %s' %
                             source[match.start():match.start() + 120]) from error
        # A source line break in a filename represents a space. Preserve other
        # spaces, since they can be significant in an actual filesystem path.
        filename = remove_comments(source[argument_start + 1:offset - 1])
        filename = re.sub(r'\s*[\r\n]+\s*', ' ', filename).strip()
        commands.append(Graphic(filename, match.start(), offset))
    return commands


def normalize_display_math(source):
    """Convert literal display delimiters to equation environments."""
    active = mask_comments(source)
    parts = []
    offset = 0
    opened = None
    for match in re.finditer(r'\$\$|\\\[|\\\]', active):
        if is_escaped(active, match.start()):
            continue
        token = match.group()
        if token == r'\]':
            if opened != r'\[':
                raise ValueError(r'Unmatched display-math delimiter \]')
            replacement = r'\end{equation}'
            opened = None
        elif token == '$$' and opened == '$$':
            replacement = r'\end{equation}'
            opened = None
        elif opened is None:
            opened = token
            replacement = r'\begin{equation}'
        else:
            raise ValueError('Mismatched display-math delimiters')
        parts.extend((source[offset:match.start()], replacement))
        offset = match.end()
    if opened is not None:
        raise ValueError('Unclosed display-math delimiter %s' % opened)
    parts.append(source[offset:])
    return ''.join(parts)


def preprocess(source, *, appendix=False, stop_comment=DEFAULT_STOP_COMMENT):
    lines = []
    for line in source.splitlines(keepends=True):
        if has_stop_comment(line, stop_comment):
            lines.append('\\end{document}\n')
            break
        lines.append(strip_latex_comment(line))
    source = ''.join(lines)
    stops = [r'\\bibliography\b', r'\\end\s*\{document\}']
    if not appendix:
        stops.append(r'\\appendix\b')
    stop = next(command_matches('|'.join(stops), source), None)
    if stop:
        source = source[:stop.start()] + '\\end{document}\n'
    # Preserve the existing workaround for txfonts, which conflicts with
    # wordcount.tex. Leave other package declarations intact.
    source = re.sub(r'(?<!\\)\\usepackage\s*(?:\[[^\]]*\]\s*)?\{txfonts\}', '', source)
    return normalize_display_math(source)


def add_documentclass_option(source, option):
    pattern = re.compile(r'\\documentclass\s*(?:\[([^\]]*)\]\s*)?(?=\{)')
    match = next(command_matches(pattern, source), None)
    if match is None:
        raise ValueError(r'Could not find \documentclass')
    options = [part.strip() for part in (match[1] or '').split(',') if part.strip()]
    if option not in options:
        options.append(option)
    return (source[:match.start()] + r'\documentclass[' + ','.join(options) + ']' +
            source[match.end():])


def tabular_body_start(document, span):
    """Skip the tabular/array width, position, and column specification."""
    active = document.active
    offset = skip_space(active, span.body_start)
    # tabular*, tabularx take a width before their optional position.
    if span.name in ('tabular*', 'tabularx'):
        _, offset = read_group(active, offset)
        offset = skip_space(active, offset)
    if offset < len(active) and active[offset] == '[':
        _, offset = read_group(active, offset, '[', ']')
    _, offset = read_group(active, offset)  # column specification
    return offset


def iter_rows(document, start=0, end=None):
    """Yield nonempty rows, preserving nested environments as structural nodes.

    Only top-level row separators split rows. Braced arguments protect their
    contents; comments, table rules, and row-spacing options do not create rows.
    Nested environments are skipped using the shared index, without rescanning
    the remaining source. Their heights are left for the counter to evaluate.
    """
    active = document.active
    end = len(active) if end is None else end
    offset = row_start = start
    children = []
    content = False
    depth = 0
    while offset < end:
        environment = document._environment_at.get(offset)
        if environment is not None:
            children.append(environment)
            content = True
            offset = environment.end
            continue
        rule = TABLE_RULE_RE.match(active, offset, end)
        if rule:
            offset = rule.end()
            continue
        if active.startswith('\\\\', offset) and depth == 0:
            if content:
                yield Row(row_start, offset, tuple(children))
            offset = skip_space(active, offset + 2)
            if offset < end and active[offset] == '*':
                offset = skip_space(active, offset + 1)
            if offset < end and active[offset] == '[':
                _, offset = read_group(active, offset, '[', ']')
            row_start = offset
            children = []
            content = False
            continue
        command = CONTROL_SEQUENCE_RE.match(active, offset, end)
        if command:
            content = True
            offset = command.end()
            continue
        char = active[offset]
        if char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
            if depth < 0:
                raise ValueError('Unmatched closing brace in row near line %d' %
                                 (active.count('\n', 0, offset) + 1))
        content = content or not char.isspace()
        offset += 1
    if depth:
        raise ValueError('Unclosed brace in row near line %d' %
                         (active.count('\n', 0, row_start) + 1))
    if content:
        yield Row(row_start, end, tuple(children))
